export { LEGACY_ICONS };

export const iconOf = (name: string | undefined): PhosphorIcon => ICONS[name ?? ""] ?? ICONS[LEGACY_ICONS[name ?? ""] ?? ""] ?? Check;

export type { IconWeight };

/** One icon by name, at a weight (thin to fill, or duotone) */
export function StoreIcon({ name, weight = "regular", className }: { name: string | undefined; weight?: IconWeight; className?: string }) {
  return createElement(iconOf(name), { weight, className, "aria-hidden": true });
}
